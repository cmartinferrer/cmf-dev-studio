from unittest.mock import Mock, call

from multi_agent_software_team.models import Mission, MissionStatus
from multi_agent_software_team.orchestrator import Orchestrator


def test_orchestrator_completes_mission():
    """Verify that the orchestrator completes a mission successfully.

    A mission starts in PENDING status. After the sequential workflow
    finishes, the orchestrator must update its status to COMPLETED.
    """
    mission = Mission(description="Create a prime number validator")
    orchestrator = Orchestrator()

    result = orchestrator.run(mission)

    assert result.status == MissionStatus.COMPLETED


def test_orchestrator_returns_original_mission():
    """Verify that the orchestrator returns the same Mission instance.

    Agents collaborate by modifying a shared Mission object.
    The orchestrator must return that same instance rather than
    creating a separate result object.
    """
    mission = Mission(description="Create a prime number validator")
    orchestrator = Orchestrator()

    result = orchestrator.run(mission)

    assert result is mission


def test_orchestrator_executes_agents_in_order():
    """Verify that agents execute in the expected sequence.

    The workflow must execute the analyst first, followed by the
    developer and finally the tester.

    Mock agents allow us to inspect execution order independently
    of their actual implementations.
    """
    mission = Mission(description="Create a prime number validator")
    orchestrator = Orchestrator()

    execution_tracker = Mock()

    orchestrator.analyst.execute = execution_tracker.analyst
    orchestrator.developer.execute = execution_tracker.developer
    orchestrator.tester.execute = execution_tracker.tester

    orchestrator.run(mission)

    assert execution_tracker.mock_calls == [
        call.analyst(mission),
        call.developer(mission),
        call.tester(mission),
    ]


def test_orchestrator_passes_same_mission_to_all_agents():
    """Verify that every agent receives the shared Mission instance.

    Each agent must operate on the same mission so that information
    generated by earlier agents remains available to later agents.
    """
    mission = Mission(description="Create a prime number validator")
    orchestrator = Orchestrator()

    orchestrator.analyst.execute = Mock()
    orchestrator.developer.execute = Mock()
    orchestrator.tester.execute = Mock()

    orchestrator.run(mission)

    orchestrator.analyst.execute.assert_called_once_with(mission)
    orchestrator.developer.execute.assert_called_once_with(mission)
    orchestrator.tester.execute.assert_called_once_with(mission)


def test_orchestrator_produces_complete_mission_output():
    """Verify that the complete workflow produces all expected outputs.

    This integration test uses the real simulated agents rather than
    mocks. It confirms that the analyst generates requirements,
    the developer generates code, and the tester generates tests.
    """
    mission = Mission(description="Create a prime number validator")
    orchestrator = Orchestrator()

    result = orchestrator.run(mission)

    assert result.requirements
    assert result.code.strip()
    assert result.tests.strip()
    assert result.status == MissionStatus.COMPLETED