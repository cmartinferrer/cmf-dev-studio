"""Docker-backed test execution for generated Python code."""

import subprocess
import tempfile
from pathlib import Path
from uuid import uuid4

from multi_agent_software_team.runner.models import TestResult, TestStatus


class DockerTestRunner:
    """Execute generated Python tests inside a restricted Docker container.

    The runner prepares a temporary workspace and delegates test execution
    to Docker. Container cleanup is checked before reporting success.

    Docker configuration alone is not a complete security boundary.
    Do not execute untrusted code until isolation has been reviewed.
    """

    def __init__(self, image: str = "multi-agent-test-runner:latest") -> None:
        """Initialize the runner with a Docker image.

        Args:
            image: Docker image used to execute Python tests.
        """
        self.image = image

    def build_command(
        self,
        workspace: str,
        container_name: str | None = None,
    ) -> list[str]:
        """Build the Docker command for isolated test execution.

        Args:
            workspace: Directory containing generated Python files.
            container_name: Optional name assigned to the Docker container.

        Returns:
            Docker command represented as a list of arguments.
        """
        workspace_path = Path(workspace).resolve()

        command = [
            "docker",
            "run",
            "--rm",
            "--network=none",
            "--read-only",
            "--cap-drop=ALL",
            "--security-opt=no-new-privileges",
            "--memory=256m",
            "--cpus=1",
            "--pids-limit=64",
            "--user=10001:10001",
            "--ipc=none",
            "--ulimit=nofile=64:64",
            "--env=PYTHONDONTWRITEBYTECODE=1",
            "--env=PYTEST_DISABLE_PLUGIN_AUTOLOAD=1",
            "--mount",
            f"type=bind,source={workspace_path},target=/workspace,readonly",
            "--tmpfs",
            "/tmp:rw,noexec,nosuid,size=64m",
            "--workdir",
            "/workspace",
            self.image,
            "python",
            "-m",
            "pytest",
            "-q",
            "-p",
            "no:cacheprovider",
        ]

        if container_name is not None:
            command[3:3] = ["--name", container_name]

        return command

    def prepare_workspace(
        self,
        workspace: Path,
        code: str,
        tests: str,
    ) -> None:
        """Write generated Python code and tests into the workspace.

        Args:
            workspace: Directory used for isolated test execution.
            code: Python implementation generated by the developer.
            tests: Pytest tests generated by the tester.
        """
        workspace.mkdir(parents=True, exist_ok=True)

        (workspace / "solution.py").write_text(
            code,
            encoding="utf-8",
        )

        (workspace / "test_solution.py").write_text(
            tests,
            encoding="utf-8",
        )

    def run(self, code: str, tests: str) -> TestResult:
        """Execute generated tests and check Docker container cleanup.

        A cleanup failure overrides a successful test result because
        the absence of the container could not be confirmed.

        Args:
            code: Python source code generated by the developer.
            tests: Pytest source code generated by the tester.

        Returns:
            A TestResult describing the execution and cleanup outcome.
        """
        workspace_root = Path.cwd() / ".runner-workspaces"
        workspace_root.mkdir(parents=True, exist_ok=True)

        with tempfile.TemporaryDirectory(
            prefix="multi-agent-tests-",
            dir=workspace_root,
        ) as directory:
            workspace = Path(directory)

            self.prepare_workspace(
                workspace=workspace,
                code=code,
                tests=tests,
            )

            container_name = f"multi-agent-test-{uuid4().hex}"

            command = self.build_command(
                workspace=str(workspace),
                container_name=container_name,
            )

            try:
                process = subprocess.run(
                    command,
                    capture_output=True,
                    text=True,
                    timeout=30,
                    check=False,
                )
                # Docker uses 125-127 for invocation/runtime failures. A
                # daemon connection error may also exit with code 1, so
                # classify that conservatively as infrastructure failure.
                docker_error = (
                    process.returncode in (125, 126, 127)
                    or (
                        process.returncode != 0
                        and any(marker in (process.stderr or "").lower() for marker in (
                            "cannot connect to the docker daemon",
                            "failed to connect to the docker api",
                            "is the docker daemon running",
                        ))
                    )
                )
                status = (
                    TestStatus.INFRASTRUCTURE_ERROR if docker_error
                    else TestStatus.PASSED if process.returncode == 0
                    else TestStatus.TEST_FAILED
                )
                result = TestResult(
                    success=status is TestStatus.PASSED,
                    exit_code=process.returncode,
                    stdout=process.stdout,
                    stderr=process.stderr,
                    status=status,
                )
            except FileNotFoundError as exc:
                result = TestResult(
                    success=False,
                    exit_code=-1,
                    stdout="",
                    stderr=f"Docker execution failed: {exc}",
                    status=TestStatus.INFRASTRUCTURE_ERROR,
                )
            except subprocess.TimeoutExpired as exc:
                result = TestResult(
                    success=False,
                    exit_code=-1,
                    stdout="",
                    stderr=f"Docker execution timed out after {exc.timeout} seconds",
                    status=TestStatus.INFRASTRUCTURE_ERROR,
                )
            finally:
                cleanup_confirmed = self.cleanup_container(container_name)

            if not cleanup_confirmed:
                return TestResult(
                    success=False,
                    exit_code=-1,
                    stdout=result.stdout,
                    stderr=(result.stderr + "\n" if result.stderr else "")
                    + f"Docker cleanup could not be confirmed for {container_name}",
                    status=TestStatus.INFRASTRUCTURE_ERROR,
                )

            return result

    def cleanup_container(self, container_name: str) -> bool:
        """Attempt to remove a container and confirm its absence.

        The container may already have been removed by Docker's --rm
        option. The removal command's exit code alone is therefore
        insufficient to establish whether cleanup succeeded.

        Args:
            container_name: Unique name of the container to remove.

        Returns:
            True if Docker confirms the container is absent.
            False if it still exists or its state cannot be determined.
        """
        try:
            subprocess.run(
                ["docker", "rm", "--force", container_name],
                capture_output=True,
                text=True,
                timeout=10,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired):
            return False

        return self.container_exists(container_name) is False

    def container_exists(self, container_name: str) -> bool | None:
        """Check whether a Docker container exists.

        Args:
            container_name: Unique name of the container to inspect.

        Returns:
            True if Docker confirms that the container exists.
            False if Docker explicitly reports that it does not exist.
            None if the container state cannot be determined.
        """
        try:
            process = subprocess.run(
                [
                    "docker",
                    "container",
                    "inspect",
                    "--format",
                    "{{.Id}}",
                    container_name,
                ],
                capture_output=True,
                text=True,
                timeout=10,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired):
            return None

        if process.returncode == 0:
            return True

        error_message = process.stderr.lower()

        if any(
            marker in error_message
            for marker in ("no such object", "no such container")
        ):
            return False

        return None